import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import riders_song  # noqa: E402

PNAMES = {"E0": "P_E0", "E1": "P_E0 + 1", "E2": "P_E0 + 2", "E3": "P_E0 + 3", "E4": "P_E0 + 4", "E5": "P_E0 + 5",
          "E6": "P_E0 + 6", "E7": "P_E0 + 7", "RING": "P_RING"}


def parse(text):
    s = dict(bpm=0, sound=[None] * 4, level=[104] * 4, param=[], timing={}, notes=[], rhythm=[], rows=[])
    slot = None
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        w = line.split()
        if w[0] == "bpm":
            s["bpm"] = int(w[1])
        elif w[0] == "sound":
            s["sound"][int(w[1])] = (int(w[2]), " ".join(w[3:]))
        elif w[0] == "level":
            s["level"][int(w[1])] = int(w[2])
        elif w[0] == "param":
            s["param"].append((int(w[1]), PNAMES[w[2]], int(w[3])))
        elif w[0] == "slot":
            slot = int(w[1])
        elif w[0] == "pat":
            s["timing"][(slot, int(w[1]))] = tuple(int(x) for x in w[2:5])
        elif w[0] == "n":
            k, st, nt, ln, v = (int(x) for x in w[1:6])
            r = int(w[6]) if len(w) > 6 else 1
            s["notes"].append((slot, k, st, nt, ln, v, r))
        elif w[0] == "mpreset":
            s["rhythm"].append((slot, int(w[1]), int(w[2]), " ".join(w[3:])))
        elif w[0] == "row":
            s["rows"].append(tuple(int(x) for x in w[1:6]))
        elif w[0] in ("save", "secs", "master"):
            pass
        else:
            raise SystemExit(f"gen_riders_song: ? {line}")
    return s


def header(s):
    o = ["/* generated by tools/gen_riders_song.py from tools/riders_song.py: do not edit */",
         f"#define RS_BPM {s['bpm']}u", f"#define RS_NNOTE {len(s['notes'])}u",
         f"#define RS_NRHYTHM {len(s['rhythm'])}u", f"#define RS_NROW {len(s['rows'])}u",
         f"#define RS_NPARAM {len(s['param'])}u",
         "static const struct { uint8_t engine; const char *preset; uint8_t level; } RS_SOUND[NTRK] = {"]
    o += [f"    {{{e}, \"{p}\", {s['level'][k]}}}," for k, (e, p) in enumerate(s["sound"])]
    o += ["};", "static const struct { uint8_t track; uint8_t id; int8_t value; } RS_PARAM[RS_NPARAM] = {"]
    o += [f"    {{{k}, {pid}, {v}}}," for k, pid, v in s["param"]]
    o += ["};", "static const uint8_t RS_TIMING[4][NTRK][3] = {   /* each slot's tracks: DIV LEN GATE */"]
    for sl in range(4):
        o.append("    {" + ", ".join("{%d, %d, %d}" % s["timing"][(sl, k)] for k in range(4)) + "},")
    o += ["};", "/* slot << 6 | track << 4 | ratchet - 1, step, note, steps held, velocity */",
          "static const uint8_t RS_NOTE[RS_NNOTE][5] = {"]
    row = []
    for sl, k, st, nt, ln, v, r in s["notes"]:
        row.append("{%d, %d, %d, %d, %d}" % (sl << 6 | k << 4 | (r - 1), st, nt, ln, v))
        if len(row) == 6:
            o.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        o.append("    " + ", ".join(row) + ",")
    o += ["};", "static const struct { uint8_t slot, track, step; const char *preset; } RS_RHYTHM[RS_NRHYTHM] = {"]
    o += [f"    {{{sl}, {k}, {st}, \"{p}\"}}," for sl, k, st, p in s["rhythm"]]
    o += ["};", "static const uint8_t RS_ROW[RS_NROW][NTRK + 1] = {   /* each track's slot (4: silent), repeats */"]
    o += ["    {" + ", ".join(str(x) for x in r) + "}," for r in s["rows"]]
    o += ["};", "#define RS_THEME_SLOT 1u   /* the pattern the scene leaves in the tracks (the theme) */", ""]
    return "\n".join(o)


if __name__ == "__main__":
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "build/gen/riders_song.h")
    s = parse(riders_song.score("chaos"))
    assert all(s["sound"]) and len(s["rows"]) <= 16 and all(sl < 4 for sl, *_ in s["notes"])
    out.write_text(header(s))
    print(f"riders song: {len(s['notes'])} notes, {len(s['rhythm'])} rhythm changes, {len(s['rows'])} sections -> {out}")
