"""The RAPTOR boot splash from the owner's artwork (assets/logo/raptor-splash-art.png: the raptor in headphones in a
ring, the wordmark, the version, the credits): the whole 240 x 240 screen, in the format splash.c reads (SLOOP's names,
SLOOP_SPLASH_*): 16 colours (RGB565), RLE runs of (run - 1) << 4 | colour. The dark scanline texture behind is taken
to black (it would not survive 16 colours, and costs flash).

  tools/gen_raptor_splash.py OUT.h            firmware boot splash
  tools/gen_raptor_splash.py --png OUT.png    a preview of what the screen shows (2x)
"""
import sys
from pathlib import Path

from PIL import Image

ART = Path(__file__).resolve().parent.parent / "assets" / "logo" / "raptor-splash-art.png"
W = H = 240
FLOOR = 60                                        # a pixel whose brightest channel is under this: black


def quantized():
    im = Image.open(ART).convert("RGB").resize((W, H), Image.LANCZOS)
    px = im.load()
    for y in range(H):
        for x in range(W):
            if max(px[x, y]) < FLOOR:
                px[x, y] = (0, 0, 0)
    return im.quantize(16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)


def rgb565(c):
    r, g, b = c
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def splash_header(path):
    q = quantized()
    pal = q.getpalette()[:48]
    cols = [tuple(pal[i:i + 3]) for i in range(0, 48, 3)]
    cols += [(0, 0, 0)] * (16 - len(cols))
    px = list(q.tobytes())
    blk = min(range(16), key=lambda k: sum(cols[k]))  # splash.c leaves colour 0 unpainted (the black canvas): black there
    if blk:
        cols[0], cols[blk] = cols[blk], cols[0]
        px = [blk if p == 0 else 0 if p == blk else p for p in px]
    rle = bytearray()
    i = 0
    while i < len(px):
        j = i
        while j < len(px) and px[j] == px[i] and j - i < 16:
            j += 1
        rle.append(((j - i - 1) << 4) | px[i])
        i = j
    L = ["/* generated by tools/gen_raptor_splash.py: the RAPTOR boot splash (splash.c reads SLOOP's names) */",
         "#pragma once", "#include <stdint.h>", "#define RAPTOR_SPLASH_FULL 1",
         f"#define SLOOP_SPLASH_W {W}", f"#define SLOOP_SPLASH_H {H}",
         "static const uint16_t SLOOP_SPLASH_PAL[16] = {" + ", ".join(f"0x{rgb565(c):04X}" for c in cols) + "};",
         f"static const uint8_t SLOOP_SPLASH_RLE[{len(rle)}] = {{"]
    for k in range(0, len(rle), 24):
        L.append("    " + ", ".join(str(b) for b in rle[k:k + 24]) + ",")
    L.append("};")
    Path(path).write_text("\n".join(L) + "\n")
    print(f"logo: RAPTOR splash {W}x{H}, {len(rle)} B RLE -> {path}")


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--png":
        quantized().convert("RGB").resize((W * 2, H * 2), Image.NEAREST).save(sys.argv[2])
    elif len(sys.argv) == 2:
        splash_header(sys.argv[1])
    else:
        sys.exit(__doc__)
