"""Packs the phrase files into paleo/engine/phrase_bank.h, from which the conductor's melody generator (motifs.h) cuts its motifs.

Reads every *-travel.txt, *-majesty.txt, *-danger.txt and *-coda.txt under pd/ and written/ (check.py format).
No single file gives more than CAP phrases to a kind (picked evenly through the file), so one big source
cannot drown out the others. Phrases with wild jumps are left out (see smooth()).

Packing, one phrase after another: kind (0 travel, 1 majesty, 2 danger, 3 coda), note count, then for each
note its degree + 16 and the index of its length in kBankBeats. The bank ends with 255.
Usage: bank.py [CAP]"""
import sys, os, glob
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from check import parse
BEATS = [0.25, .5, .75, 1, 1.5, 2, 3, 4, 6]
KINDS = ["travel", "majesty", "danger", "coda"]
CHANT_CAP = 10000
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "engine", "phrase_bank.h")

def smooth(p, kind):
    """Singable: no leap over an octave, at most one leap of a sixth or more (two for majesty), not a run of fast
    notes (piano figures; danger may be quicker), and not a zig-zag that turns at nearly every note."""
    jumps = [abs(p[i + 1][0] - p[i][0]) for i in range(len(p) - 1)]
    if max(jumps) > 7 or sum(1 for j in jumps if j >= 5) > (2 if kind == "majesty" else 1): return False
    fast = sum(1 for _, b in p if b <= .25) / len(p)
    if fast > (.5 if kind == "danger" else .25): return False
    moves = [p[i + 1][0] - p[i][0] for i in range(len(p) - 1) if p[i + 1][0] != p[i][0]]
    turns = sum(1 for i in range(len(moves) - 1) if (moves[i] > 0) != (moves[i + 1] > 0))
    if len(moves) >= 5 and turns / (len(moves) - 1) > .75: return False
    return True

def main():
    cap = int(sys.argv[1]) if len(sys.argv) > 1 else 40000
    data = bytearray(); counts = {k: 0 for k in KINDS}; files = []
    for ki, kind in enumerate(KINDS):
        for f in sorted(glob.glob(os.path.join(HERE, "pd", "*-%s.txt" % kind)) + glob.glob(os.path.join(HERE, "written", "*-%s.txt" % kind))):
            songs = {}                                         # source -> its phrases, in the order they come
            for l in open(f, encoding="utf-8"):
                if l.lstrip().startswith("#"): continue
                p = parse(l)
                if p and smooth(p, kind): songs.setdefault(l.split("#", 1)[1].strip() if "#" in l else "", []).append(p)
            c = min(cap, CHANT_CAP) if "chant" in os.path.basename(f) else cap   # chant's even rhythm in moderation
            # whole songs are kept together, picked evenly through the file, so a tune's phrases follow each other
            keys = list(songs); ps = []
            if sum(len(v) for v in songs.values()) > c:
                order = sorted(range(len(keys)), key=lambda i: (i * 2654435761) % len(keys))
                for i in order:
                    if len(ps) + len(songs[keys[i]]) > c: continue
                    ps += songs[keys[i]]
            else:
                for k in keys: ps += songs[k]
            files.append("%s: %d" % (os.path.relpath(f, HERE), len(ps)))
            for p in ps:
                data += bytes([ki, len(p)])
                for d, b in p: data += bytes([d + 16, BEATS.index(b)])
            counts[kind] += len(ps)
    data.append(255)
    with open(OUT, "w") as o:
        o.write("/* SPDX-License-Identifier: GPL-3.0-only */\n")
        o.write("/* Generated by paleo/phrases/bank.py: do not edit. Melody phrases from real music, for the motifs of\n")
        o.write("   the conductor's melody generator. Sources and credits: paleo/phrases/SOURCES.md.\n")
        for line in files: o.write("     %s\n" % line)
        o.write("   travel %d, majesty %d, danger %d, coda %d phrases. */\n" % tuple(counts[k] for k in KINDS))
        o.write("#pragma once\n#include <cstdint>\n")
        o.write("static const float kBankBeats[9] = {.25f, .5f, .75f, 1, 1.5f, 2, 3, 4, 6};\n")
        o.write("static const uint8_t kPhraseBank[%d] = {\n" % len(data))
        for i in range(0, len(data), 40):
            o.write(",".join(str(x) for x in data[i:i + 40]) + ",\n")
        o.write("};\n")
    print("wrote %s: %d bytes, %s" % (os.path.relpath(OUT, HERE), len(data), counts))

if __name__ == "__main__":
    main()
